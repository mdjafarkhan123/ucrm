-- The public file route's one seam: a token hash in, the file's storage pointer out (or nothing, on any
-- failure -- unknown token and "not found" must look identical to a stranger). Records first_viewed_at on
-- the first successful resolve, same idea as job_report_access_links' own view marker.
create or replace function public.resolve_communication_sms_attachment_access_link(
  supplied_token_hash bytea
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  link_row public.communication_sms_attachment_access_links;
  attachment_row public.communication_outbound_attachments;
begin
  if supplied_token_hash is null or octet_length(supplied_token_hash) <> 32 then
    return null;
  end if;

  select * into link_row
  from public.communication_sms_attachment_access_links
  where token_hash = supplied_token_hash;
  if link_row.id is null then
    return null;
  end if;

  select * into attachment_row
  from public.communication_outbound_attachments
  where id = link_row.attachment_id and organization_id = link_row.organization_id;
  if attachment_row.id is null then
    return null;
  end if;

  update public.communication_sms_attachment_access_links
  set first_viewed_at = coalesce(first_viewed_at, now())
  where id = link_row.id;

  return jsonb_build_object(
    'object_key', attachment_row.object_key,
    'mime_type', attachment_row.mime_type,
    'file_name', attachment_row.file_name
  );
end;
$$;

revoke all on function public.resolve_communication_sms_attachment_access_link(bytea)
