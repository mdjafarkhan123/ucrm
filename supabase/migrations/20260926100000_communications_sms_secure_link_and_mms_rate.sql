-- ---------------------------------------------------------------------------------------------------------------
-- 3. The link itself. One row per attachment that went the secure-link route -- there is never a staff
--    "create link" action to mirror (issued automatically inside the enqueue command), so this table carries
--    no issued_by, no rotation and no expiry, matching Jafar's 2026-09-16 answer.
-- ---------------------------------------------------------------------------------------------------------------
create table public.communication_sms_attachment_access_links (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  delivery_intent_id uuid not null,
  attachment_id uuid not null,
  -- The SHA-256 of a 256-bit random token, as raw bytes -- same shape as quote_access_links.token_hash.
  token_hash bytea not null check (octet_length(token_hash) = 32),
  issued_at timestamptz not null default now(),
  first_viewed_at timestamptz,
  constraint communication_sms_attachment_access_links_token_hash_unique unique (token_hash),
  constraint communication_sms_attachment_access_links_intent_fk
    foreign key (organization_id, delivery_intent_id)
    references public.communication_delivery_intents (organization_id, id) on delete cascade,
  constraint communication_sms_attachment_access_links_attachment_fk
    foreign key (organization_id, attachment_id)
    references public.communication_outbound_attachments (organization_id, id) on delete cascade
);

comment on table public.communication_sms_attachment_access_links is
  'One customer link per SMS attachment that could not go as real MMS media. Issued automatically inside '
  'communication_sms_enqueue_operational_core, not by a staff action -- no expiry, no rotation (Jafar '
  '2026-09-16: matches the no-expiry precedent quote/invoice links already use). Stores only the token hash; '
  'the raw token exists once, in the link text baked into the frozen SMS body.';

