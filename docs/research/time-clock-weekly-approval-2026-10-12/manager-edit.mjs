import { chromium } from '/home/jafar/Ucrm/node_modules/playwright/index.mjs';
import { readFile } from 'node:fs/promises';
const origin = 'http://localhost:5174';
const login = await readFile('/home/jafar/Ucrm/Login.md', 'utf8');
const [, email, password] = login.match(/Contractor owner: `([^`]+)` \/\s*`([^`]+)`/);
const fieldId = '7d450c50-b3e5-4f97-8ee9-50e08c1f70bb';
const browser = await chromium.launch();
const page = await (await browser.newContext()).newPage();
await page.goto(`${origin}/login`); await page.waitForLoadState('networkidle'); await page.waitForTimeout(1500);
await page.locator('input[type=email]').fill(email); await page.locator('input[type=password]').fill(password);
await page.getByRole('button', { name: /sign in/i }).click();
await page.waitForURL((u) => !u.pathname.startsWith('/login'), { timeout: 60000 });
const summary = await (await page.request.get(`${origin}/api/time-clock/timesheets?span=day`)).json();
const tz = summary.timezone;
const { entries } = await (await page.request.get(`${origin}/api/time-clock/timesheets/entries?${new URLSearchParams({ user_id: fieldId, from: '2026-10-11', to: '2026-10-11' })}`)).json();
const e = entries.find((x) => x.approved && x.job);
const hm = (iso) => new Intl.DateTimeFormat('en-GB', { timeZone: tz, hour: '2-digit', minute: '2-digit', hour12: false }).format(new Date(iso));
const body = { user_id: fieldId, job_id: e.job.id, visit_id: e.visit_id, day: e.started_on, start_time: hm(e.started_at), end_time: hm(e.ended_at), notes: 'Checked by office (approval proof)' };
const r = await page.request.patch(`${origin}/api/time-clock/timesheets/entries/${e.id}`, { data: body });
console.log('manager PATCH', r.status(), (await r.text()).slice(0, 200));
const after = (await (await page.request.get(`${origin}/api/time-clock/timesheets/entries?${new URLSearchParams({ user_id: fieldId, from: '2026-10-11', to: '2026-10-11' })}`)).json()).entries.find((x) => x.id === e.id);
console.log('still approved', after.approved, 'notes', after.notes, 'minutes', e.minutes, '->', after.minutes);
const h = await (await page.request.get(`${origin}/api/time-clock/timesheets/entries/${e.id}/history`)).json();
console.log('history', JSON.stringify(h).slice(0, 900));
await browser.close();
