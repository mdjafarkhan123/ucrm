-- Stage 10 Part 5d (docs/global-sms-behavior-contract.md § Part 5): quiet hours on the customer's clock.
--
-- Until now the platform quiet window (21:00–08:00) was read in one time zone, New York, so a customer in Dhaka
-- could be texted at 3am. Now the window is read where the customer is, worked out from their phone number the
-- way Google libphonenumber's PhoneNumberToTimeZonesMapper does: the longest matching leading digits give the
-- number's possible time zones (+1 212 is New York; +880 is Dhaka; +52 alone is all of Mexico).
--
-- 1. Phone number time zones. Rows come from scripts/generate-phone-time-zones.mjs (libphonenumber v9.0.41).
-- 2. When a text may go: the first moment that is outside the quiet window in every time zone the number can
--    be in. Numbers whose zones never share a daytime (a bare +1 spans Guam to Alaska) fall back to the
--    platform zone, as before.
-- 3. Enqueue and dispatch pass the customer's number. Their bodies are unchanged otherwise.

