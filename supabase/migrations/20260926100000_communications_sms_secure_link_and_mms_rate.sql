-- 2. communication_outbound_attachments gains delivery_mode, so the SMS worker knows which rows to hand to
--    Twilio as MediaUrl (a real MMS photo) versus which rows were only ever described by a link already
--    baked into the frozen message body. Email attachments are always 'inline_media' -- the only channel
--    this distinction has ever applied to is SMS.
-- ---------------------------------------------------------------------------------------------------------------
alter table public.communication_outbound_attachments
