-- 2. When a text may go ----------------------------------------------------------------------------------------

-- The end of the quiet window in one time zone when p_at falls inside it, otherwise p_at.
create or replace function private.sms_quiet_window_end(
  p_at timestamptz, p_zone text, p_quiet_start time, p_quiet_end time
)
returns timestamptz
language plpgsql
immutable
set search_path = pg_catalog
as $$
declare
  local_ts timestamp := p_at at time zone p_zone;
  local_time time := local_ts::time;
  in_window boolean;
begin
  if p_quiet_start <= p_quiet_end then
    in_window := local_time >= p_quiet_start and local_time < p_quiet_end;
  else
    -- Window wraps midnight: quiet from quiet_start to end-of-day and from start-of-day to quiet_end.
    in_window := local_time >= p_quiet_start or local_time < p_quiet_end;
  end if;

  if not in_window then
    return p_at;
  end if;
  if local_time < p_quiet_end then
    -- In the early-morning tail of the window: the end is later today (local).
    return (local_ts::date + p_quiet_end) at time zone p_zone;
  end if;
  -- At or after quiet_start: the end is tomorrow morning (local).
  return ((local_ts::date + 1) + p_quiet_end) at time zone p_zone;
end;
$$;

revoke all on function private.sms_quiet_window_end(timestamptz, text, time, time) from public, anon, authenticated;

create or replace function public.communication_sms_quiet_hours_available_at(
  p_at timestamptz, p_recipient_e164 text
)
returns timestamptz
language plpgsql
stable
security definer
set search_path = pg_catalog, public, private
as $$
declare
  policy public.communication_sms_quiet_hours_policy;
  zones text[];
  tz text;
  candidate timestamptz := p_at;
  moved boolean;
begin
  select * into policy from public.communication_sms_quiet_hours_policy where id;
  if not found or not policy.enabled then
    return p_at;
  end if;

  zones := coalesce(private.sms_phone_time_zones(p_recipient_e164), array[policy.time_zone]);

  -- Push the send past each zone's night until no zone moves it. Zones a few hours apart settle in two or
  -- three passes; zones with no shared daytime never settle.
  for pass in 1..8 loop
    moved := false;
    foreach tz in array zones loop
      if private.sms_quiet_window_end(candidate, tz, policy.quiet_start, policy.quiet_end) > candidate then
        candidate := private.sms_quiet_window_end(candidate, tz, policy.quiet_start, policy.quiet_end);
        moved := true;
      end if;
    end loop;
    if not moved then
      return candidate;
    end if;
  end loop;

  return private.sms_quiet_window_end(p_at, policy.time_zone, policy.quiet_start, policy.quiet_end);
end;
$$;

