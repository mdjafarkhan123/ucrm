-- Communications Stage 6D-3: MMS pricing + secure-link fallback for a picture/file that cannot go as real
-- MMS (a non-image file, or a picture whose sender/destination is not US/Canada). Closes 6D-2's placeholder
-- refusal ("Picture messaging is not available for this number yet.") with the behavior 6D was actually
-- approved for on 2026-09-12: "supported pictures send/arrive as MMS where country/sender/destination allow
-- it; other files use approved secure links; explain why when unavailable."
--
-- Jafar approved 2026-09-16 (asked directly, not guessed): the composer's attach control is always available
-- for any common file, not gated on MMS eligibility; a picture goes as real MMS when eligible, otherwise the
-- text carries a secure link -- same as any other file type. The link never expires, matching how quote and
-- invoice customer links already work (no rotation/expiry infrastructure invented here).
--
-- Money: MMS bills Twilio as one flat unit per message, not per segment (confirmed against Twilio's own
-- pricing pages -- a picture text is priced as "1 MMS" regardless of how much text rides with it, unlike a
-- plain SMS which bills per 153/70-character segment). This adds 'mms' as a second message_unit next to the
-- existing 'segment', publishable through the same Jafar-owned communication_sms_set_retail_rate the SMS
-- segment rate already uses -- no new pricing mechanism.
--
-- The secure link reuses the exact token pattern already proven by quotes/invoices/job reports (256-bit
-- random token, only its SHA-256 hash ever reaches the database, one resolver function, streamed through our
-- own server so no raw storage URL is ever exposed) -- not a new invention. Unlike those, this link is issued
-- automatically at send time inside the enqueue command itself (no staff "create link" action), so the token
-- is generated by the TS caller *before* the RPC call and passed in as part of the attachment payload; the
-- database only ever sees the hash and the ready-made link URL text to embed in the message body.

